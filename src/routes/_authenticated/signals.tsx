import { createFileRoute } from "@tanstack/react-router";
import { Panel, DemoTag } from "@/components/AppShell";
import { useDemoMarket } from "@/lib/use-demo";

export const Route = createFileRoute("/_authenticated/signals")({
  head: () => ({
    meta: [
      { title: "Signal History — GoldScalp AI" },
      { name: "description", content: "History of demo BUY and SELL signals generated by the GoldScalp AI strategy." },
      { property: "og:title", content: "Signal History — GoldScalp AI" },
      { property: "og:description", content: "Demo XAU/USD scalping signal history." },
    ],
  }),
  component: History,
});

function History() {
  const { signals } = useDemoMarket();
  return (
    <Panel title={`Signal history (${signals.length})`} right={<DemoTag />}>
      {signals.length === 0 && <p className="text-sm text-muted-foreground">No signals with current settings.</p>}
      <ul className="divide-y">
        {signals.map((s) => (
          <li key={s.id} className="grid grid-cols-[auto_minmax(0,1fr)] items-center gap-3 py-3 text-sm sm:grid-cols-[auto_1fr_1fr_1fr_1fr]">
            <span className={`w-14 rounded px-2 py-1 text-center text-xs font-bold ${s.side === "BUY" ? "bg-bull/15 text-bull" : "bg-bear/15 text-bear"}`}>{s.side}</span>
            <span className="num text-muted-foreground">{new Date(s.time).toISOString().slice(5, 16).replace("T", " ")}</span>
            <span className="num col-span-2 sm:col-span-1">Entry {s.entryLow.toFixed(2)}–{s.entryHigh.toFixed(2)}</span>
            <span className="num text-bear">SL {s.sl.toFixed(2)}</span>
            <span className="num text-bull">TP {s.tp.toFixed(2)} · 1:{s.rr.toFixed(1)}</span>
          </li>
        ))}
      </ul>
    </Panel>
  );
}
